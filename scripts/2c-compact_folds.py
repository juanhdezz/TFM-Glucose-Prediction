"""2c-compact_folds.py — Reconstruct full-fold parquets from per-fold balanced outputs.

Takes the per-fold parquet files produced by 2b-trainset_balancing.py and
merges them back into single-file datasets that are directly compatible with
3-train.py.

For every (dataset, horizon, demographic group, technique) combination the
script:
    1. Reads the original fold parquet (produced by 2-folds_creation.py) as
       the authoritative source for val/test rows and fold column structure.
    2. For each fold index (0-4) reads the corresponding balanced parquet from
       balanced_outputs/ and extracts only the rows labelled 'train' for that
       fold.
    3. Combines:
           - val/test rows from the ORIGINAL (never modified)
           - balanced train rows from each fold's balanced file
       into a single DataFrame with all five fold columns.
    4. Writes the result as a single parquet named
           {dataset_name}_balanced_{group}_{technique}_PH{horizon}.parquet
       into data/{dataset_name}/ alongside the original fold file.

Val/test integrity guarantee
----------------------------
Val and test rows are ALWAYS taken from the original parquet, never from the
balanced files. The sanity check C3 verifies that the val/test count for every
fold column matches the original exactly.

Synthetic row handling
----------------------
Rows generated by oversampling, jittering or SMOTE exist only for a specific
fold. Their fold columns for OTHER folds are set to 'train' as a safe
placeholder. This is harmless because 3-train.py filters by fold_i when
processing fold i and never uses those rows in fold j (j != i).

Usage examples
--------------
# Process everything with defaults
python 2c-compact_folds.py

# Only DiaTrend, sex group, smote technique
python 2c-compact_folds.py --datasets DIATREND --groups sex --techniques smote

# Specify a different data root
python 2c-compact_folds.py --data-root /opt/data

# Overwrite existing output files
python 2c-compact_folds.py --overwrite
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import pandas as pd

# ---------------------------------------------------------------------------
# Constants — kept in sync with 2b-trainset_balancing.py defaults
# ---------------------------------------------------------------------------

ROOT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT_DIR / "data"

DEFAULT_FOLDS = [0, 1, 2, 3, 4]
DEFAULT_GROUPS = ["sex", "age"]
DEFAULT_TECHNIQUES = [
    "undersampling",
    "oversampling",
    "patient_aware_undersampling",
    "smote",
    "jittering",
    "reference_proportional",
]
DEFAULT_HORIZONS = [4]

# Fold column prefix written by 2-folds_creation.py
FOLD_COLUMN_PREFIX = "fold_"

# Label used in fold columns for training rows
TRAIN_LABEL = "train"

# Feature and target columns consumed by 3-train.py (must be preserved exactly)
FEATURE_COLS = [f"x{i}" for i in range(8)]
TARGET_COL = "y"

# Demographic helper columns added by 2b — must NOT appear in the final output
DEMOGRAPHIC_COLS = ["sex_group", "age", "age_group"]


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class BalancedKey:
    """Identifies a unique (dataset, horizon, group, technique) combination."""
    dataset_name: str
    horizon: int
    group: str
    technique: str


@dataclass
class FoldFile:
    """A single per-fold balanced parquet produced by 2b."""
    fold_idx: int
    path: Path


@dataclass
class CompactionJob:
    """Everything needed to compact one (dataset, horizon, group, technique)."""
    key: BalancedKey
    original_parquet: Path       # produced by 2-folds_creation.py
    fold_files: List[FoldFile]   # one per fold index, from balanced_outputs/
    output_path: Path            # where the compacted parquet will be written


