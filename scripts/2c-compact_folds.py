def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Compact per-fold balanced parquets into single-file datasets "
            "compatible with 3-train.py."
        )
    )
    parser.add_argument(
        "--data-root",
        type=str,
        default=str(DATA_DIR),
        help="Root directory that contains the dataset sub-folders.",
    )
    parser.add_argument(
        "--datasets",
        nargs="*",
        default=None,
        help="Dataset folder names to process. Defaults to all sub-folders.",
    )
    parser.add_argument(
        "--groups",
        nargs="*",
        default=DEFAULT_GROUPS,
        choices=DEFAULT_GROUPS,
        help="Demographic group columns to compact.",
    )
    parser.add_argument(
        "--techniques",
        nargs="*",
        default=DEFAULT_TECHNIQUES,
        choices=DEFAULT_TECHNIQUES,
        help="Balancing techniques to compact.",
    )
    parser.add_argument(
        "--horizons",
        nargs="*",
        type=int,
        default=DEFAULT_HORIZONS,
        help="Prediction horizons to process.",
    )
    parser.add_argument(
        "--folds",
        nargs="*",
        type=int,
        default=DEFAULT_FOLDS,
        help="Fold indices to compact (must match what 2b produced).",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing output files.",
    )
    return parser.parse_args()


# ---------------------------------------------------------------------------
# File discovery helpers
# ---------------------------------------------------------------------------

def discover_dataset_dirs(root: Path, dataset_names: Optional[Sequence[str]]) -> List[Path]:
    """Return dataset directories under root, optionally filtered by name."""
    if dataset_names:
        dirs = [root / name for name in dataset_names]
    else:
        dirs = [p for p in sorted(root.iterdir()) if p.is_dir()]
    return [d for d in dirs if d.exists()]


def find_original_parquet(dataset_dir: Path, dataset_name: str, horizon: int) -> Optional[Path]:
    """
    Locate the original fold parquet written by 2-folds_creation.py.

    Naming pattern (from tag_folds_and_save in 2-folds_creation.py):
        windows_with_5folds_{dataset_name}*PH{horizon}*.parquet
    Falls back to any parquet matching windows_with_5folds_{dataset_name}.
    """
    patterns = [
        f"windows_with_5folds_{dataset_name}*PH{horizon}*.parquet",
        f"windows_with_5folds_{dataset_name}*.parquet",
    ]
    for pattern in patterns:
        candidates = sorted(dataset_dir.glob(pattern))
        if candidates:
            return candidates[0]
    return None


def parse_balanced_filename(filename: str) -> Optional[Tuple[int, str, str]]:
    """
    Extract (fold_idx, group, technique) from a balanced parquet filename.

    2b-trainset_balancing.py names outputs as:
        {windows_stem}_fold{idx}_{group}_{technique}.parquet

    where windows_stem itself may contain underscores, so we parse from the
    right using a fixed-suffix regex.

    Returns None if the filename does not match the expected pattern.
    """
    stem = Path(filename).stem
    # Match _fold{digits}_{group}_{technique} at the END of the stem.
    # group is a single lowercase word (sex, age).
    # technique may contain underscores (patient_aware_undersampling).
    pattern = re.compile(
        r"_fold(?P<fold>\d+)"
        r"_(?P<group>[a-z]+)"
        r"_(?P<technique>[a-z_]+)$"
    )
    match = pattern.search(stem)
    if not match:
        return None
    return int(match.group("fold")), match.group("group"), match.group("technique")


def discover_compaction_jobs(
    dataset_dir: Path,
    dataset_name: str,
    horizon: int,
    groups: Sequence[str],
    techniques: Sequence[str],
    folds: Sequence[int],
) -> List[CompactionJob]:
    """
    Scan balanced_outputs/ for per-fold parquets and group them into
    CompactionJob instances — one per (group, technique) combination for which
    all requested fold files are present.
    """
    balanced_dir = dataset_dir / "balanced_outputs"
    if not balanced_dir.exists():
        print(f"  [WARN] balanced_outputs/ not found in {dataset_dir}; skipping.")
        return []

    original = find_original_parquet(dataset_dir, dataset_name, horizon)
    if original is None:
        print(f"  [WARN] Original fold parquet not found in {dataset_dir}; skipping.")
        return []

    horizon_stem_fragment = f"PH{horizon}"
    available: Dict[Tuple[str, str], Dict[int, Path]] = {}

    for path in sorted(balanced_dir.glob("*.parquet")):
        if horizon_stem_fragment not in path.name:
            continue
        parsed = parse_balanced_filename(path.name)
        if parsed is None:
            continue
        fold_idx, group, technique = parsed
        if group not in groups or technique not in techniques:
            continue
        if fold_idx not in folds:
            continue
        key = (group, technique)
        available.setdefault(key, {})[fold_idx] = path

    jobs: List[CompactionJob] = []
    for (group, technique), fold_map in available.items():
        missing = [f for f in folds if f not in fold_map]
        if missing:
            print(
                f"  [WARN] ({group}, {technique}): missing fold files for folds "
                f"{missing}; skipping this combination."
            )
            continue

        output_name = (
            f"{dataset_name}_balanced_{group}_{technique}_PH{horizon}.parquet"
        )
        output_path = dataset_dir / output_name

        jobs.append(
            CompactionJob(
                key=BalancedKey(dataset_name, horizon, group, technique),
                original_parquet=original,
                fold_files=[
                    FoldFile(fold_idx=f, path=fold_map[f])
                    for f in sorted(folds)
                ],
                output_path=output_path,
            )
        )

    return jobs


# ---------------------------------------------------------------------------
# Column helpers
# ---------------------------------------------------------------------------

def strip_demographic_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Remove demographic helper columns if present."""
    return df.drop(columns=[c for c in DEMOGRAPHIC_COLS if c in df.columns])


def normalise_fold_columns(df: pd.DataFrame, fold_cols: Sequence[str]) -> pd.DataFrame:
    """
    Convert fold columns to plain str dtype.

    Pandas category dtype can cause silent mismatches when concatenating
    DataFrames that have different category sets.  We normalise to str here
    and restore category at the end of compact_one_job.
    """
    df = df.copy()
    for col in fold_cols:
        if col in df.columns:
            df[col] = df[col].astype(str)
    return df


def validate_fold_columns(df: pd.DataFrame, folds: Sequence[int]) -> List[str]:
    """
    Return the fold column names present in df for the requested fold indices.
    Raises ValueError if any expected fold column is missing.
    """
    expected = [f"{FOLD_COLUMN_PREFIX}{i}" for i in folds]
    missing = [col for col in expected if col not in df.columns]
    if missing:
        raise ValueError(
            f"Original parquet is missing fold columns: {missing}. "
            f"Available columns: {list(df.columns)}"
        )
    return expected


# ---------------------------------------------------------------------------
# Sanity checks
# ---------------------------------------------------------------------------

def run_sanity_checks(
    result_df: pd.DataFrame,
    original_df: pd.DataFrame,
    fold_cols: Sequence[str],
    key: BalancedKey,
) -> None:
    """
    Verify the compacted DataFrame before writing.

    Hard failures (raise ValueError, abort write):
        C1 — required columns present
        C3 — val/test counts match original exactly for every fold
        C4 — no demographic columns in output

    Soft warnings (print only):
        C2 — NaN in feature/target columns (edge case in SMOTE)
        C5 — zero train rows in some fold
        C6 — column set matches original
    """
    print("    Running sanity checks...")
    prefix = f"    [CHECK] ({key.group}, {key.technique})"

    # C1 — required columns present
    required = FEATURE_COLS + [TARGET_COL, "patient_id"] + list(fold_cols)
    missing_cols = [c for c in required if c not in result_df.columns]
    if missing_cols:
        raise ValueError(
            f"{prefix} Missing required columns in output: {missing_cols}"
        )
    print(f"      ✓ C1: all required columns present")

    # C2 — NaN in feature/target (soft)
    nan_total = result_df[FEATURE_COLS + [TARGET_COL]].isna().sum().sum()
    if nan_total > 0:
        print(
            f"      ⚠ C2: {nan_total} NaN values in feature/target columns "
            f"(possible SMOTE edge case — verify before training)."
        )
    else:
        print(f"      ✓ C2: no NaN values in feature/target columns")

    # C3 — val/test counts match original (hard)
    for fold_col in fold_cols:
        for label in ("val", "test"):
            orig_count  = (original_df[fold_col].astype(str) == label).sum()
            result_count = (result_df[fold_col].astype(str) == label).sum()
            if orig_count != result_count:
                raise ValueError(
                    f"{prefix} {fold_col}/{label} count mismatch: "
                    f"original={orig_count:,}, result={result_count:,}. "
                    f"Val/test rows must not be modified by compaction."
                )
    print(f"      ✓ C3: val/test counts match original for all folds")

    # C4 — no demographic columns leaked (hard)
    leaked = [c for c in DEMOGRAPHIC_COLS if c in result_df.columns]
    if leaked:
        raise ValueError(
            f"{prefix} Demographic columns found in output: {leaked}."
        )
    print(f"      ✓ C4: no demographic columns in output")

    # C5 — train rows per fold (soft)
    for fold_col in fold_cols:
        train_count = (result_df[fold_col].astype(str) == TRAIN_LABEL).sum()
        if train_count == 0:
            print(
                f"      ⚠ C5: {fold_col} has 0 train rows — "
                f"the model will have nothing to learn in this fold."
            )
        else:
            print(f"      ✓ C5: {fold_col} train rows = {train_count:,}")

    # C6 — column set matches original (soft)
    orig_cols   = set(original_df.columns)
    result_cols = set(result_df.columns)
    extra   = result_cols - orig_cols
    missing = orig_cols - result_cols
    if extra:
        print(f"      ⚠ C6: extra columns in output (ignored by 3-train.py): {extra}")
    if missing:
        print(f"      ⚠ C6: columns in original missing from output: {missing}")
    if not extra and not missing:
        print(f"      ✓ C6: output column set matches original exactly")


# ---------------------------------------------------------------------------
# Core reconstruction logic
# ---------------------------------------------------------------------------

def compact_one_job(job: CompactionJob, folds: Sequence[int], overwrite: bool) -> bool:
    """
    Reconstruct a full-fold parquet for one (group, technique) combination.

    Design
    ------
    The original parquet has ONE row per window, with all five fold columns
    populated.  A given row can be 'train' in fold_0 but 'val' in fold_1.

    The balanced file for fold_i contains:
        - balanced train rows for fold_i  (may include synthetic rows)
        - ALL val/test rows from the original for fold_i

    The key insight that fixes the previous bug:

        Val/test rows MUST always come from the original, never from the
        balanced files.  The balanced file for fold_i includes the val/test
        rows of fold_i in its 'untouched' portion, but those same rows may
        be 'train' in fold_j (j != i), causing double-counting if we naively
        concatenate the untouched portions across all folds.

    Correct assembly:
        result = original_valtest_rows          # rows that are val/test in
                                                # at least one fold, taken
                                                # directly from the original
               + balanced_train(fold_0)         # train rows for each fold
               + balanced_train(fold_1)         # from the balanced files
               + ...
               + balanced_train(fold_4)

    For synthetic train rows (not present in the original) the fold columns
    for OTHER folds are set to TRAIN_LABEL as a safe placeholder.
    3-train.py only reads fold_i when processing fold i, so those
    placeholder values are never used in another fold's experiment.

    Returns True if a file was written, False if skipped.
    """
    k = job.key

    if job.output_path.exists() and not overwrite:
        print(
            f"  [SKIP] Output already exists: {job.output_path.name} "
            f"(use --overwrite to replace)"
        )
        return False

    print(f"\n  Compacting: {k.dataset_name} | PH={k.horizon} | {k.group} | {k.technique}")
    print(f"    Original  : {job.original_parquet.name}")

    # ------------------------------------------------------------------
    # Step 1 — load the original parquet
    # ------------------------------------------------------------------
    original_df = pd.read_parquet(job.original_parquet)
    original_df = strip_demographic_columns(original_df)
    fold_cols   = validate_fold_columns(original_df, folds)
    original_df = normalise_fold_columns(original_df, fold_cols)

    print(f"    Original rows: {len(original_df):,}")

    # ------------------------------------------------------------------
    # Step 2 — extract val/test rows from the original
    #
    # A row belongs to the val/test pool if it is NOT 'train' in at least
    # one fold.  We keep these rows exactly as they appear in the original
    # (all five fold columns intact).
    # ------------------------------------------------------------------
    is_valtest_in_any_fold = pd.Series(False, index=original_df.index)
    for fold_col in fold_cols:
        is_valtest_in_any_fold |= (original_df[fold_col] != TRAIN_LABEL)

    original_valtest = original_df.loc[is_valtest_in_any_fold].copy()
    print(f"    Val/test pool (from original): {len(original_valtest):,} rows")

    # ------------------------------------------------------------------
    # Step 3 — for each fold, read balanced train rows
    # ------------------------------------------------------------------
    train_parts: List[pd.DataFrame] = []

    for fold_file in job.fold_files:
        fold_idx = fold_file.fold_idx
        fold_col = f"{FOLD_COLUMN_PREFIX}{fold_idx}"

        print(f"    Fold {fold_idx}: reading {fold_file.path.name}")

        balanced_df = pd.read_parquet(fold_file.path)
        balanced_df = strip_demographic_columns(balanced_df)
        balanced_df = normalise_fold_columns(balanced_df, fold_cols)

        # Extract only the rows labelled 'train' for this fold
        train_rows = balanced_df.loc[
            balanced_df[fold_col] == TRAIN_LABEL
        ].copy()

        print(
            f"      Original train size (fold {fold_idx}): "
            f"{(original_df[fold_col] == TRAIN_LABEL).sum():,}"
        )
        print(f"      Balanced train size (fold {fold_idx}): {len(train_rows):,}")

        if len(train_rows) == 0:
            print(
                f"      [WARN] No train rows found for fold {fold_idx} "
                f"in {fold_file.path.name}."
            )

        # For synthetic rows the other fold columns carry stale values
        # from the fold_i balanced file.  Overwrite them with TRAIN_LABEL
        # so they never accidentally appear as val/test in another fold.
        other_fold_cols = [c for c in fold_cols if c != fold_col]
        for col in other_fold_cols:
            train_rows[col] = TRAIN_LABEL

        train_parts.append(train_rows)

    # ------------------------------------------------------------------
    # Step 4 — assemble final DataFrame
    # ------------------------------------------------------------------
    result_df = pd.concat(
        [original_valtest] + train_parts,
        ignore_index=True,
    )

    # Restore category dtype on fold columns (matches original schema)
    for fold_col in fold_cols:
        result_df[fold_col] = result_df[fold_col].astype("category")

    # ------------------------------------------------------------------
    # Step 5 — sanity checks
    # ------------------------------------------------------------------
    run_sanity_checks(result_df, original_df, fold_cols, k)

    # ------------------------------------------------------------------
    # Step 6 — write output
    # ------------------------------------------------------------------
    job.output_path.parent.mkdir(parents=True, exist_ok=True)
    result_df.to_parquet(job.output_path, index=False)

    print(f"    ✓ Written: {job.output_path.name}  ({len(result_df):,} rows)")
    return True


# ---------------------------------------------------------------------------
# Per-dataset orchestration
# ---------------------------------------------------------------------------

def process_dataset(
    dataset_dir: Path,
    dataset_name: str,
    horizons: Sequence[int],
    groups: Sequence[str],
    techniques: Sequence[str],
    folds: Sequence[int],
    overwrite: bool,
) -> Tuple[int, int]:
    """Process all compaction jobs for a single dataset.

    Returns (files_written, files_skipped).
    """
    written = skipped = 0

    for horizon in horizons:
        jobs = discover_compaction_jobs(
            dataset_dir=dataset_dir,
            dataset_name=dataset_name,
            horizon=horizon,
            groups=groups,
            techniques=techniques,
            folds=folds,
        )

        if not jobs:
            print(
                f"  No compaction jobs found for {dataset_name} / PH={horizon} "
                f"with the requested groups and techniques."
            )
            continue

        print(f"\n  Found {len(jobs)} compaction job(s) for PH={horizon}")

        for job in jobs:
            try:
                did_write = compact_one_job(job, folds, overwrite)
                if did_write:
                    written += 1
                else:
                    skipped += 1
            except Exception as exc:
                print(
                    f"  [ERROR] Failed to compact "
                    f"({job.key.group}, {job.key.technique}): {exc}"
                )

    return written, skipped


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main() -> None:
    args = parse_args()
    root = Path(args.data_root)

    if not root.exists():
        print(f"[ERROR] Data root does not exist: {root}")
        sys.exit(1)

    dataset_dirs = discover_dataset_dirs(root, args.datasets)
    if not dataset_dirs:
        print(f"[ERROR] No dataset directories found under {root}")
        sys.exit(1)

    total_written = total_skipped = 0

    for dataset_dir in dataset_dirs:
        dataset_name = dataset_dir.name
        print(f"\n{'='*60}")
        print(f"Dataset: {dataset_name}")
        print(f"{'='*60}")

        written, skipped = process_dataset(
            dataset_dir=dataset_dir,
            dataset_name=dataset_name,
            horizons=args.horizons,
            groups=args.groups,
            techniques=args.techniques,
            folds=args.folds,
            overwrite=args.overwrite,
        )
        total_written += written
        total_skipped += skipped

    print(f"\n{'='*60}")
    print(f"Compaction complete.")
    print(f"  Files written : {total_written}")
    print(f"  Files skipped : {total_skipped}")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()